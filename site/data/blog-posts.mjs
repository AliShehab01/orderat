/** Rough reading time in minutes at ~180 Arabic words/minute, minimum 2. */
export function readingMinutes(post) {
  const words = post.ar.sections.flatMap((s) => s.paragraphs.join(" ").split(/\s+/)).length;
  return Math.max(2, Math.round(words / 180));
}
